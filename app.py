def money(n: float) -> str:
    a = abs(n)
    s = "-" if n < 0 else ""
    if a >= 1e7:
        return f"{s}₹{a/1e7:.2f} Cr"
    if a >= 1e5:
        return f"{s}₹{a/1e5:.2f} L"
    return f"{s}₹{a:,.0f}"


# ---------------------------------------------------------------------------
# Cached heavy work — Streamlit reruns the script on every interaction
# ---------------------------------------------------------------------------

@st.cache_data(show_spinner=False)
def load_sample() -> pd.DataFrame:
    return acc.load_ledger(SAMPLE)


@st.cache_data(show_spinner=False)
def run_validation(raw: pd.DataFrame):
    return acc.validate(raw)


@st.cache_data(show_spinner=False)
def get_model(df: pd.DataFrame):
    """
    cache_data, not cache_resource. cache_resource does not hash its argument,
    so the cache key would be empty: upload ledger A then ledger B and tab 3
    would silently serve A's model, A's metrics and A's error table — which
    includes A's transaction descriptions — alongside B's figures.
    """
    return train(df)


@st.cache_data(show_spinner=False)
def get_anomalies(df: pd.DataFrame) -> pd.DataFrame:
    return detect(df)


