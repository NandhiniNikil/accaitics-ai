# 3. SMART CATEGORISATION
# ===========================================================================
with tabs[2]:
    st.subheader("Smart expense categorisation")

    labelled = df[(df["txn_type"] == "Expense") &
                  (df["category"] != "Uncategorised")]
    if len(labelled) < 40:
        st.warning("Not enough labelled expense rows to train a model. The "
                   "categoriser needs a `category` column with at least 40 "
                   "labelled expense transactions.")
    else:
        with st.spinner("Training on labelled transactions…"):
            r = get_model(df)

        c1, c2, c3, c4 = st.columns(4)
        c1.metric("Model accuracy", f"{r['ml_accuracy']:.1%}")
        c2.metric("Macro F1", f"{r['ml_macro_f1']:.3f}")
        c3.metric("Rule baseline F1", f"{r['rule_macro_f1']:.3f}",
                  f"{r['ml_macro_f1'] - r['rule_macro_f1']:+.3f} vs ML")
        c4.metric("Held-out rows", f"{r['n_test']}")

        if r["beats_rules"]:
            st.success(f"The model beats the keyword rule baseline "
                       f"({r['ml_macro_f1']:.3f} vs {r['rule_macro_f1']:.3f} "
                       f"macro-F1) on this data.")
        else:
            st.info(
                f"**The keyword rules beat the model on this data** "
                f"({r['rule_macro_f1']:.3f} vs {r['ml_macro_f1']:.3f} macro-F1), "
                f"and they are {r['rule_precision_when_fired']:.0%} correct on the "
                f"{r['rule_coverage']:.0%} of rows they fire on — their "
                f"{r['rule_abstentions']} errors are all abstentions, while the "
                f"model makes {r['ml_miscodings']} confident miscodings.\n\n"
                f"The model stays in because the rules were hand-written against "
                f"this wording. On descriptions neither has seen, the rules fire "
                f"on under half and the model is right about three quarters of the "
                f"time. **What ships is rules first, model filling the gaps.**")

        st.markdown("##### The automation trade-off")
        st.caption("Accuracy alone is not useful. If you cannot tell *which* "
                   "predictions are right, every row needs checking anyway. So "
                   "the model reports a confidence and only auto-posts above a "
                   "threshold tuned to keep posted entries ~99% correct.")

        tt = r["threshold_table"]
        tfig = go.Figure()
        tfig.add_scatter(x=tt["threshold"], y=tt["auto_post_pct"] * 100,
                         name="% auto-posted", mode="lines+markers",
                         line=dict(color=FOREST, width=2.5))
        tfig.add_scatter(x=tt["threshold"], y=tt["auto_post_accuracy"] * 100,
                         name="Accuracy of auto-posted", mode="lines+markers",
                         line=dict(color=GOLD, width=2.5))
        tfig.add_vline(x=r["threshold"], line_dash="dash", line_color=BAD,
                       annotation_text=f"chosen {r['threshold']:.2f}")
        tfig.update_layout(height=320, plot_bgcolor="white",
                           margin=dict(l=10, r=10, t=30, b=10),
                           yaxis_title="%", xaxis_title="Confidence threshold",
                           legend=dict(orientation="h", y=1.15, x=0))
        tfig.update_yaxes(gridcolor="#E8E3D8")
        st.plotly_chart(tfig, width="stretch")

        c1, c2, c3 = st.columns(3)
        c1.metric("Auto-posted", f"{r['auto_post_pct']:.0%}")
        c2.metric("Accuracy when auto-posted", f"{r['auto_post_accuracy']:.1%}")
        c3.metric("Sent for human review", f"{r['review_pct']:.0%}")
        st.caption(f"Threshold {r['threshold']:.2f}, chosen by "
                   f"{r['threshold_chosen_by']} — never on the rows it is scored "
                   f"against.")

        st.markdown("##### Try it on a description")
        txt = st.text_input("Transaction description",
                            "ELECTRICITY BL PYMT 4471",
                            help="Type anything a bookkeeper might write.")
        if txt.strip():
            s = suggest(r["model"], [txt], r["threshold"]).iloc[0]
            a, b, c, d = st.columns(4)
            a.metric("Suggested category", s["suggested_category"])
            b.metric("Decided by", s["decided_by"])
            c.metric("Confidence", f"{s['confidence']:.0%}")
            d.metric("Action", s["action"])
            if s["decided_by"] == "Keyword rule":
                st.caption("A keyword rule matched, so the model was not consulted "
                           "— rules are exact where they fire.")
            else:
                st.caption("No keyword rule matched, so the model filled the gap. "
                           "Its confidence decides whether this posts or goes to "
                           "a person.")

        st.markdown("##### Where the model gets it wrong")
        st.caption("High-confidence mistakes are the dangerous ones. Most of "
                   "these are genuinely ambiguous entries — the text alone does "
                   "not contain the answer, so routing them to a human is the "
                   "correct behaviour.")
        st.dataframe(r["errors"].head(12), width="stretch", hide_index=True)

        st.markdown("##### Per-category performance")
        st.dataframe(r["per_category"].round(3), width="stretch")

# ===========================================================================
# 4. REVIEW QUEUE
# ===========================================================================
with tabs[3]:
    st.subheader("Transactions for review")
    st.markdown('<div class="disclaimer"><b>A flag is a question, not an '
                'accusation.</b> These entries look unusual compared with the '
                'rest of the ledger. Several will be perfectly legitimate. '
                'Anomaly detection without confirmed labels cannot establish '
                'fraud, and this tool does not claim to.</div>',
                unsafe_allow_html=True)
    st.write("")

    with st.spinner("Scoring transactions…"):
        scored = get_anomalies(df)

    flagged = scored[scored["is_flagged"]]
    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Flagged for review", f"{len(flagged)}")
    c2.metric("Share of expenses", f"{len(flagged)/max(len(scored),1):.1%}")
    c3.metric("Value under review", money(flagged["amount"].sum()))
    c4.metric("Rule + model signals", f"{int(flagged['signals'].sum())}")

    if len(flagged):
        min_sig = st.slider("Minimum number of signals", 1,
                            int(max(2, flagged["signals"].max())), 1,
                            help="Rows flagged by more independent checks are "
                                 "more likely to be genuine findings.")
        view = flagged[flagged["signals"] >= min_sig]

        show = view[["transaction_id", "date", "description", "category",
                     "vendor", "amount", "signals", "reason"]].copy()
        show["date"] = show["date"].dt.strftime("%d %b %Y")
        show["amount"] = show["amount"].map(lambda v: f"₹{v:,.2f}")
        st.dataframe(show, width="stretch", hide_index=True, height=420)

        st.download_button("Download review queue (CSV)",
                           view.to_csv(index=False).encode(),
                           "accaitics_review_queue.csv", "text/csv")

        st.markdown("##### Where the flags sit")
        sc = go.Figure()
        normal = scored[~scored["is_flagged"]]
        sc.add_scatter(x=normal["date"], y=normal["amount"], mode="markers",
                       name="Normal", marker=dict(color="#C9C2B2", size=5))
        sc.add_scatter(x=flagged["date"], y=flagged["amount"], mode="markers",
                       name="Flagged", marker=dict(color=BAD, size=9,
                                                   line=dict(width=1, color="white")),
                       text=flagged["reason"])
        sc.update_layout(height=340, plot_bgcolor="white",
                         margin=dict(l=10, r=10, t=30, b=10), yaxis_title="₹",
                         legend=dict(orientation="h", y=1.13, x=0))
        sc.update_yaxes(gridcolor="#E8E3D8", type="log")
        st.plotly_chart(sc, width="stretch")
        st.caption("Amount on a log scale, because expense amounts are heavily "
                   "right-skewed — a materials bill is naturally far larger than "
                   "a stationery bill.")
    else:
        st.success("Nothing flagged. No entry sits far outside the normal range "
                   "for its own ledger head.")

# ===========================================================================
# 5. ASK FINANCE
# ===========================================================================
with tabs[4]:
    st.subheader("Ask Finance")
    st.caption("Questions are matched to a calculation, which runs against your "
               "ledger. The answer shows its own arithmetic. No language model "
               "produces a figure here.")

    if "chat" not in st.session_state:
        st.session_state.chat = []

    cols = st.columns(4)
    for i, q in enumerate(ask_mod.SAMPLE_QUESTIONS[:8]):
        if cols[i % 4].button(q, key=f"sq{i}", width="stretch"):
            st.session_state.pending = q

    typed = st.chat_input("Ask about your ledger…")
    pending = st.session_state.pop("pending", None)
    question = typed or pending

    if question:
        answer = ask_mod.ask(question, df)
        st.session_state.chat.append((question, answer))

    for q, a in reversed(st.session_state.chat[-8:]):
        with st.chat_message("user"):
            st.write(q)
        with st.chat_message("assistant"):
            st.write(a.text)
            if a.workings:
                with st.expander("Show the arithmetic"):
                    st.code(a.workings, language="text")
            if a.table is not None and len(a.table):
                st.dataframe(a.table.head(15), width="stretch", hide_index=True)

    if not st.session_state.chat:
        st.info("Pick a question above, or type your own.")

st.divider()
st.caption("ACCAITICS AI — portfolio project built on synthetic data. "
           "Informational assistance only; not certified accounting, tax, "
           "investment or legal advice. Verify important decisions with a "
           "qualified professional.")
